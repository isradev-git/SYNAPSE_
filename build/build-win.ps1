# build-win.ps1 — Build and package Luna for Windows
#
# Produces:
#   - luna.exe in target/release/
#   - Portable ZIP with luna.exe
#   - MSI installer (via WiX Toolset)
#
# Requirements:
#   - Rust toolchain (rustup, cargo, rustc)
#   - WiX Toolset (for MSI) — https://wixtoolset.org/
#
# Usage:
#   .\build\build-win.ps1              # dev build + zip
#   .\build\build-win.ps1 -Release     # release build + zip + msi

param(
    [switch]$Release
)

$ErrorActionPreference = "Stop"
$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$ProjectDir = Split-Path -Parent $ScriptDir
Set-Location $ProjectDir

$Version = "0.1.2"
$AppName = "Luna"
$Profile = if ($Release) { "release" } else { "debug" }
$TargetDir = "target\$Profile"

Write-Host "[1/3] Building $AppName ($Profile)..." -ForegroundColor Cyan
if ($Release) {
    cargo build --release -p Luna-app
} else {
    cargo build -p Luna-app
}

$Binary = "$TargetDir\luna.exe"
if (-not (Test-Path $Binary)) {
    Write-Error "Binary not found at $Binary"
    exit 1
}

Write-Host "[2/3] Creating portable ZIP..." -ForegroundColor Cyan
$ZipPath = "$TargetDir\$AppName-v$Version-x86_64-windows.zip"
# Use Compress-Archive for portable zip
# We put only luna.exe in the zip
if (Get-Command Compress-Archive -ErrorAction SilentlyContinue) {
    Compress-Archive -Path $Binary -DestinationPath $ZipPath -Force
    Write-Host "  ZIP: $ZipPath"
} else {
    Write-Warning "  Compress-Archive not available. Skipping ZIP."
}

Write-Host "[3/3] MSI installer..." -ForegroundColor Cyan
# The MSI is generated by cargo-dist via wix/main.wxs during CI.
# For local builds, WiX Toolset must be installed and in PATH.
# Checking for candle/light binaries:
$hasWix = Get-Command candle.exe -ErrorAction SilentlyContinue
if (-not $hasWix -and $Release) {
    Write-Warning "  WiX Toolset not found. Skipping MSI. Install from https://wixtoolset.org/"
    Write-Warning "  In CI, the MSI is built via cargo-dist + WiX GitHub Action."
} elseif ($Release) {
    Write-Host "  WiX found. Run 'cargo wix' to build MSI locally."
    Write-Host "  (MSI is normally built in CI via cargo-dist)"
}

Write-Host ""
Write-Host "Build complete: $Binary" -ForegroundColor Green
